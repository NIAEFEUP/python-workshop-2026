# Exercise 7: Multiplication Table with Early Square Stop
# Print num x i = res for i from 1 to 10. When i reaches num,
# print num ^ 2 = res and stop immediately.
#
# Example input/output:
#
#   +--------+------------------------------------------------+
#   | Input  | Output                                         |
#   +--------+------------------------------------------------+
#   | 3      | 3 x 1 = 3                                      |
#   |        | 3 x 2 = 6                                      |
#   |        | 3 ^ 2 = 9                                      |
#   +--------+------------------------------------------------+
#   | 5      | 5 x 1 = 5                                      |
#   |        | 5 x 2 = 10                                     |
#   |        | 5 x 3 = 15                                     |
#   |        | 5 x 4 = 20                                     |
#   |        | 5 ^ 2 = 25                                     |
#   +--------+------------------------------------------------+
#   | 0      | 0 x 1 = 0                                      |
#   |        | 0 x 2 = 0                                      |
#   |        | ...                                            |
#   |        | 0 x 10 = 0                                     |
#   +--------+------------------------------------------------+
#   | 11     | 11 x 1 = 11                                    |
#   |        | 11 x 2 = 22                                    |
#   |        | ...                                            |
#   |        | 11 x 10 = 110                                  |
#   +--------+------------------------------------------------+

num = int(input())
for i in range(1, 11):
    if i == num:
        print(f"{num} ^ 2 = {num * i}")
        break
    print(f"{num} x {i} = {num * i}")
